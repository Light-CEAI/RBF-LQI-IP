function rbf_export_for_embedded(matFile, outFile)
%RBF_EXPORT_FOR_EMBEDDED Convert a trained rbf_centers.mat into a plain
%   .m file with hard-coded numeric arrays — no file I/O, no load(),
%   fixed-size, MATLAB-Coder-safe. THIS is what actually ships to the
%   target. rbf_centers.mat / rbf_initialize.m's load() path is HOST-SIDE
%   ONLY (simulation, training, iteration) and must never be reached by
%   any code you generate for the MCU.
%
%   Run once, after rbf_train_offline.m, before building the embedded
%   target:
%       rbf_export_for_embedded('rbf_centers.mat', 'rbf_centers_const.m');

if nargin < 1 || isempty(matFile),  matFile = 'rbf_centers.mat'; end
if nargin < 2 || isempty(outFile),  outFile = 'rbf_centers_const.m'; end

s = load(matFile);
centers = s.centers;
weights = s.weights;
[n_hidden, n_inputs] = size(centers);

fid = fopen(outFile, 'w');
fprintf(fid, 'function [centers, weights] = rbf_centers_const()\n');
fprintf(fid, '%%RBF_CENTERS_CONST Auto-generated by rbf_export_for_embedded.m\n');
fprintf(fid, '%%  DO NOT EDIT BY HAND. Re-run the export after re-training.\n');
fprintf(fid, '%%  Source: %s, generated %s\n\n', matFile, datestr(now));

fprintf(fid, 'centers = coder.const(single([\n');
for r = 1:n_hidden
    fprintf(fid, '    %s;\n', strjoin(arrayfun(@(c) sprintf('%.8f', c), centers(r,:), ...
        'UniformOutput', false), ', '));
end
fprintf(fid, ']));\n\n');

fprintf(fid, 'weights = coder.const(single([\n');
fprintf(fid, '    %s\n', strjoin(arrayfun(@(w) sprintf('%.8f', w), weights(:)', ...
    'UniformOutput', false), '; '));
fprintf(fid, ']));\n\n');
fprintf(fid, 'end\n');
fclose(fid);

fprintf('Exported %dx%d centers and %d weights to %s\n', n_hidden, n_inputs, n_hidden, outFile);
fprintf('coder.const() marks these as compile-time constants, so MATLAB Coder\n');
fprintf('folds them into flash/ROM rather than allocating runtime memory.\n');

end