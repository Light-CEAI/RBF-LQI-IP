function generate_control_consts(K, Ki, Ad, Bd, L, C_meas, params, outFile)
%GENERATE_CONTROL_CONSTS Cast offline-designed (double) LQI/observer gains
%   to single precision and write them as compile-time constants — same
%   pattern as rbf_export_for_embedded.m. NEVER call lqr/dlqe/place on
%   the target; they require the Control System Toolbox and floating
%   design-time computation that has no place running on an MCU.
%
%   Run once, after design_lqi.m / observer_design.m, before building:
%       [A,B,C,D] = linearized_model(params);
%       [Ad,Bd,Cd,Dd] = discretize_model(A,B,C,D, params.embedded.Ts);
%       [K, Ki] = design_lqi(A, B, params);
%       [L, C_meas] = observer_design(Ad, params, 'kalman');
%       generate_control_consts(K, Ki, Ad, Bd, L, C_meas, params, 'control_consts.m');

if nargin < 8 || isempty(outFile), outFile = 'control_consts.m'; end

fid = fopen(outFile, 'w');
fprintf(fid, 'function c = control_consts()\n');
fprintf(fid, '%%CONTROL_CONSTS Auto-generated by generate_control_consts.m\n');
fprintf(fid, '%%  DO NOT EDIT BY HAND. Re-run after re-design. Generated %s\n\n', datestr(now));

writeMat(fid, 'K', K);
writeMat(fid, 'Ki', Ki);
writeMat(fid, 'Ad', Ad);
writeMat(fid, 'Bd', Bd);
writeMat(fid, 'L', L);
writeMat(fid, 'C_meas', C_meas);

fprintf(fid, 'c.Ts = coder.const(single(%.8f));\n', params.embedded.Ts);

switch params.config
    case 'A'
        fprintf(fid, 'c.actuator_limit = coder.const(single(%.8f));\n', params.cart.tau_max);
    case 'B'
        fprintf(fid, 'c.actuator_limit = coder.const(single(%.8f));\n', params.cart.u_max);
end

fprintf(fid, 'c.sat_tol = coder.const(single(1e-4));\n'); % replaces eps for single-precision compares
fprintf(fid, 'end\n');
fclose(fid);

fprintf('Wrote %s — all gains cast to single precision, embedded-safe.\n', outFile);

    function writeMat(fid, name, M)
        M = single(M);
        fprintf(fid, 'c.%s = coder.const(single([\n', name);
        for r = 1:size(M,1)
            fprintf(fid, '    %s;\n', strjoin(arrayfun(@(v) sprintf('%.8f', v), M(r,:), ...
                'UniformOutput', false), ', '));
        end
        fprintf(fid, ']));\n\n');
    end
end